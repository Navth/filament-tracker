"""Turn a v1 tracker.db (Flask + SQLite) into SQL that imports its spools,
prints and adjustments into one user's account in the multi-user app.

    python scripts/import-v1.py tracker.db you@example.com > import-v1.local.sql

Run the output once in the Supabase SQL editor. It refuses to run if that
user already has spools. The Bambu token is not copied: reconnect Bambu
Cloud on the Settings page (the new app encrypts it).
"""
import json
import sqlite3
import sys


def lit(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def main(db_path, email):
    db = sqlite3.connect(f"file:{db_path}?mode=ro", uri=True)
    db.row_factory = sqlite3.Row
    config = {r["key"]: r["value"] for r in db.execute("select key, value from config")}
    spools = db.execute("select * from spools order by id").fetchall()
    prints = db.execute("select * from prints order by id").fetchall()
    adjustments = db.execute("select * from adjustments order by id").fetchall()

    out = [
        "-- Generated by scripts/import-v1.py. Contains personal data; do not commit.",
        "do $$",
        "declare",
        "  uid uuid;",
        "  ids jsonb := '{}';",
        "  new_id bigint;",
        "begin",
        f"  select id into uid from auth.users where lower(email) = lower({lit(email)});",
        f"  if uid is null then raise exception 'No user with email %', {lit(email)}; end if;",
        "  if exists (select 1 from public.spools where user_id = uid) then",
        "    raise exception 'User already has spools; import skipped';",
        "  end if;",
        "",
        "  insert into public.user_settings (user_id, slot_count, device_id, bambu_email, bambu_region, last_sync)",
        f"  values (uid, {int(config.get('slot_count') or 1)}, {lit(config.get('device_id') or '')},",
        f"          {lit(config.get('email') or '')}, {lit(config.get('region') or 'global')}, {lit(config.get('last_sync'))})",
        "  on conflict (user_id) do update set slot_count = excluded.slot_count,",
        "    device_id = excluded.device_id, bambu_email = excluded.bambu_email,",
        "    bambu_region = excluded.bambu_region, last_sync = excluded.last_sync;",
        "",
    ]
    for s in spools:
        out += [
            "  insert into public.spools (user_id, slot, brand, material, color, initial_g, note, started_at, ended_at, active)",
            f"  values (uid, {s['slot']}, {lit(s['brand'] or '')}, {lit(s['material'] or 'PLA')}, {lit(s['color'] or '')},",
            f"          {s['initial_g']}, {lit(s['note'] or '')}, coalesce({lit(s['started_at'])}::timestamptz, now()),",
            f"          {lit(s['ended_at'])}, {'true' if s['active'] else 'false'})",
            "  returning id into new_id;",
            f"  ids := ids || jsonb_build_object('{s['id']}', new_id);",
        ]
    out.append("")
    for p in prints:
        spool = "null" if p["spool_id"] is None else f"(ids->>'{p['spool_id']}')::bigint"
        out += [
            "  insert into public.prints (user_id, task_key, title, device_id, status, start_time, end_time, weight, slot, spool_id, counted, source)",
            f"  values (uid, {lit(p['task_key'])}, {lit(p['title'] or 'Untitled')}, {lit(p['device_id'])}, "
            f"{'null' if p['status'] is None else p['status']}, {lit(p['start_time'])}, {lit(p['end_time'])}, "
            f"{p['weight'] or 0}, {p['slot'] or 1}, {spool}, {'true' if p['counted'] else 'false'}, {lit(p['source'] or 'cloud')});",
        ]
    for a in adjustments:
        out += [
            "  insert into public.adjustments (user_id, spool_id, grams, note, created_at)",
            f"  values (uid, (ids->>'{a['spool_id']}')::bigint, {a['grams']}, {lit(a['note'] or '')}, "
            f"coalesce({lit(a['created_at'])}::timestamptz, now()));",
        ]
    out += [
        "",
        f"  raise notice 'Imported % spools, % prints, % adjustments', {len(spools)}, {len(prints)}, {len(adjustments)};",
        "end $$;",
    ]
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
